#!/usr/bin/env node
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = join(ROOT, 'docs', 'launch-evidence.md');
const check = process.argv.includes('--check');
const capabilities = JSON.parse(readFileSync(join(ROOT, 'docs', 'capabilities.json'), 'utf8'));
const publicContract = JSON.parse(readFileSync(join(ROOT, 'docs', 'public-contract.json'), 'utf8'));
const journeys = JSON.parse(readFileSync(join(ROOT, 'docs', 'case-studies', 'journeys', 'evidence.json'), 'utf8'));
const version = readFileSync(join(ROOT, 'VERSION'), 'utf8').trim();
const temp = mkdtempSync(join(tmpdir(), 'web-app-security-launch-'));

function heading(path) {
  const document = readFileSync(join(ROOT, path), 'utf8');
  return document.match(/^#\s+(.+)$/m)?.[1] || basename(path, '.md');
}

try {
  const demo = spawnSync(process.execPath, [join(ROOT, 'scripts', 'demo.mjs'), '--out', temp], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: 30000,
  });
  if (demo.status !== 0) throw new Error(demo.stderr || demo.stdout || 'demo failed');
  const before = JSON.parse(readFileSync(join(temp, 'before.json'), 'utf8'));
  const after = JSON.parse(readFileSync(join(temp, 'after.json'), 'utf8'));
  const severity = (report, name) => report.findings.filter((item) => item.severity === name).length;
  const grouped = Object.fromEntries(Object.keys(capabilities.labels).map((label) => [
    label, capabilities.capabilities.filter((item) => item.label === label).length,
  ]));
  if (journeys.journeys.length !== publicContract.projectJourneys.length) {
    throw new Error('project-journey structured sources disagree');
  }

  const lines = [
    '# Launch evidence',
    '',
    '<!-- Generated by scripts/generate-launch-evidence.mjs from structured sources and the real local demo. Do not edit by hand. -->',
    '',
    'This is an evidence inventory, not a security score. Counts describe versioned repository',
    'artifacts and reproduced local behavior; they do not claim universal scanner coverage.',
    '',
    '## Reproducible inventory',
    '',
    '| Surface | Reproduced evidence | Source |',
    '|---|---|---|',
    `| Capability contract | ${capabilities.capabilities.length} capabilities: ${grouped.automated_regression_tested} automated/regression-tested, ${grouped.agent_guided} agent-guided, ${grouped.planned} planned | [Generated matrix](capabilities.md) |`,
    `| Local before/after demo | ${severity(before, 'high')} high / ${severity(before, 'medium')} medium -> ${severity(after, 'high')} high / ${severity(after, 'medium')} medium | [Generated demo evidence](demo-evidence.md) |`,
    `| Ordinary project journeys | ${journeys.journeys.length} fixed-commit source journeys; no hosted instance probed | [Journey method](case-studies/journeys/README.md) |`,
    `| Source methodology studies | ${publicContract.methodStudies.length} fixed-commit studies, kept separate from CLI precision claims | [Study method](case-studies/README.md) |`,
    `| Release | v${version} signed tag, reproducible archive, SPDX SBOM, checksums, manifest and provenance | [v${version} release](https://github.com/parousia8888/web-app-security-skill/releases/tag/v${version}) |`,
    '',
    '## Ordinary project journeys',
    '',
    ...journeys.journeys.map((journey) =>
      `- [${journey.project}](${journey.document.replace(/^docs\//, '')}) at \`${journey.commit}\`: ${journey.deterministicAudit.total} deterministic finding(s), manual result \`${journey.manualTrace.classification}\`; false-positive closures and unreached surfaces are recorded.`),
    '',
    '## Source methodology studies',
    '',
    ...publicContract.methodStudies.map((path) => `- [${heading(path)}](${path.replace(/^docs\//, '')})`),
    '',
    '## Verification',
    '',
    '```bash',
    'node scripts/generate-launch-evidence.mjs --check',
    'npm run demo -- --out ./demo-output',
    'node scripts/check-case-journeys.mjs',
    'node scripts/check-p7-surfaces.mjs',
    '```',
    '',
    'A source pattern remains `suspected` until reproduced. Unavailable evidence remains `unknown`.',
    'Checksums and attestations prove artifact identity and origin, not every security conclusion.',
  ];
  const rendered = `${lines.join('\n')}\n`;
  if (check) {
    if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== rendered) {
      console.error('launch evidence is stale; run node scripts/generate-launch-evidence.mjs');
      process.exit(1);
    }
    console.log(`launch evidence current: ${capabilities.capabilities.length} capabilities, ${journeys.journeys.length} journeys, ${publicContract.methodStudies.length} studies`);
  } else {
    writeFileSync(OUTPUT, rendered);
    console.log(OUTPUT);
  }
} catch (error) {
  console.error(`launch evidence: ${error.message}`);
  process.exitCode = 1;
} finally {
  rmSync(temp, { recursive: true, force: true });
}
